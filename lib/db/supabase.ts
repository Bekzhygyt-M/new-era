/**
 * PostgreSQL backend (TZ §28).
 *
 * Mirrors the JSON store's contract exactly so the two are interchangeable —
 * the E2E suite runs against the local adapter and covers this one's semantics
 * by construction. Ids are always generated by the database, never by the app.
 */

const sb = () => supabaseAdmin();
const rows = <T>(data: unknown): T[] => (Array.isArray(data) ? (data as T[]) : []);
const first = <T>(data: unknown): T | null => (Array.isArray(data) && data.length ? (data[0] as T) : null);

/** What a PostgREST query resolves to. */
type QueryResult = { data: unknown; error: { message: string; code?: string } | null };

/**
 * The subset of the PostgREST builder this adapter uses. Declaring it exactly
 * keeps the query helpers typed without leaking `any` through every call site.
 */
interface Query extends PromiseLike<QueryResult> {
  eq(column: string, value: unknown): Query;
  neq(column: string, value: unknown): Query;
  lt(column: string, value: unknown): Query;
  in(column: string, values: readonly unknown[]): Query;
  ilike(column: string, pattern: string): Query;
  or(filter: string): Query;
  order(column: string, options?: { ascending?: boolean }): Query;
  limit(count: number): Query;
}

const from = (table: string): Query => sb().from(table).select('*') as unknown as Query;

/** Reads never insert; a missing row is null, not an error. */
async function selectOne<T>(table: string, build: (q: Query) => Query, ctx: string): Promise<T | null> {
  return first<T>(unwrap(await build(from(table)).limit(1), ctx));
}

async function selectMany<T>(table: string, build: (q: Query) => Query, ctx: string): Promise<T[]> {
  return rows<T>(unwrap(await build(from(table)), ctx));
}

async function insertOne<T>(table: string, row: Record<string, unknown>, ctx: string): Promise<T> {
  const data = unwrap(await sb().from(table).insert(defined(row)).select('*').single(), ctx);
  return data as T;
}

async function updateOne<T>(table: string, id: string, row: Record<string, unknown>, ctx: string): Promise<T> {
  const data = unwrap(await sb().from(table).update(defined(row)).eq('id', id).select('*').single(), ctx);
  return data as T;
}

async function deleteById(table: string, id: string, ctx: string): Promise<boolean> {
  const data = unwrap(await sb().from(table).delete().eq('id', id).select('id'), ctx);
  return rows(data).length > 0;
}

