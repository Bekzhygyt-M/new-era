/** Decorates payments with their course and buyer, as the model expects. */
async function attachPaymentRelations(list: LocalPayment[]): Promise<LocalPayment[]> {
  if (!list.length) return [];

  const courseIds = [...new Set(list.map((p) => p.course_id).filter(Boolean))];
  const userIds = [...new Set(list.map((p) => p.user_id).filter(Boolean))];

  const [courses, profiles] = await Promise.all([
    courseIds.length
      ? selectMany<LocalCourse>('courses', (q) => q.in('id', courseIds), 'payments:courses')
      : Promise.resolve([]),
    userIds.length
      ? selectMany<LocalProfile>('profiles', (q) => q.in('id', userIds), 'payments:profiles')
      : Promise.resolve([]),
  ]);

  const courseById = new Map(courses.map((c) => [c.id, c]));
  const profileById = new Map(profiles.map((p) => [p.id, p]));

  return list.map((p) => ({
    ...p,
    courses: courseById.get(p.course_id) || null,
    profiles: profileById.get(p.user_id) || null,
  }));
}
