// ─── Translations ────────────────────────────────────────────────────────────
// One model shape, three SQL tables — each keyed by the row it translates.

const TRANSLATION_TABLE: Record<LocalTranslation['entity'], { table: string; fk: string }> = {
  course: { table: 'course_translations', fk: 'course_id' },
  module: { table: 'module_translations', fk: 'module_id' },
  lesson: { table: 'lesson_translations', fk: 'lesson_id' },
};

function translationFromRow(entity: LocalTranslation['entity'], row: Record<string, unknown>): LocalTranslation {
  const { fk } = TRANSLATION_TABLE[entity];
  return {
    id: String(row.id ?? ''),
    entity,
    entity_id: String(row[fk] ?? ''),
    locale: row.locale === 'en' ? 'en' : 'ru',
    title: (row.title as string | null) ?? null,
    short_description: (row.short_description as string | null) ?? null,
    description: (row.description as string | null) ?? null,
    summary: (row.summary as string | null) ?? null,
    key_terms: (row.key_terms as LocalTranslation['key_terms']) ?? null,
    updated_at: String(row.updated_at ?? ''),
  };
}

/** Only the columns that table actually has — the shapes differ per entity. */
function translationToRow(t: Partial<LocalTranslation> & { entity: LocalTranslation['entity'] }): Record<string, unknown> {
  const row: Record<string, unknown> = {};
  if (t.title !== undefined) row.title = t.title;
  if (t.description !== undefined) row.description = t.description;
  if (t.entity !== 'module' && t.short_description !== undefined) row.short_description = t.short_description;
  if (t.entity === 'lesson') {
    if (t.summary !== undefined) row.summary = t.summary;
    if (t.key_terms !== undefined) row.key_terms = t.key_terms;
  }
  return row;
}

// ─── Lesson materials (TZ §11, §28) ──────────────────────────────────────────
// Stored in their own ordered table; the model still sees one array per lesson.

type MaterialRow = { lesson_id: string; title: string; url: string; type: string; order_index: number };

async function attachMaterials<T extends LocalLesson>(lessons: T[]): Promise<T[]> {
  if (!lessons.length) return lessons;

  const rows = await selectMany<MaterialRow>(
    'lesson_materials',
    (q) => q.in('lesson_id', lessons.map((l) => l.id)).order('order_index'),
    'lessonMaterials'
  );

  const byLesson = new Map<string, LocalLesson['materials']>();
  for (const row of rows) {
    const list = byLesson.get(row.lesson_id) || [];
    list.push({ title: row.title, url: row.url, type: row.type });
    byLesson.set(row.lesson_id, list);
  }

  return lessons.map((lesson) => ({ ...lesson, materials: byLesson.get(lesson.id) || [] }));
}

/** Replaces a lesson's material list; absent means "leave as is". */
async function writeMaterials(lessonId: string, materials: LocalLesson['materials']) {
  if (materials === undefined) return;

  unwrap(
    await sb().from('lesson_materials').delete().eq('lesson_id', lessonId).select('id'),
    'lessonMaterials:clear'
  );
  if (!materials.length) return;

  unwrap(
    await sb()
      .from('lesson_materials')
      .insert(
        materials.map((m, index) => ({
          lesson_id: lessonId,
          title: m.title,
          url: m.url,
          type: m.type || 'file',
          order_index: index + 1,
        }))
      )
      .select('id'),
    'lessonMaterials:insert'
  );
}

